export type TranslationKey = keyof typeof translations.tr;

export const usePreferences = defineStore("preferences", () => {
  const locale = ref<"tr" | "en">("tr");
  const theme = ref<"dark" | "light">("dark");
  const page = ref<TranslationKey>("landingTitle");
  watch(
    [locale, theme, page],
    () => {
      document.documentElement.lang = locale.value;
      document.documentElement.dataset.theme = theme.value;
      document
        .querySelector('meta[name="theme-color"]')
        ?.setAttribute("content", theme.value === "dark" ? "#0e0f0f" : "#f6f3eb");
      document.title = `Cord · ${translations[locale.value][page.value]}`;
    },
    { immediate: true },
  );
  function t(key: TranslationKey, values: Record<string, string> = {}) {
    return Object.entries(values).reduce<string>(
      (text, [name, value]) => text.replaceAll(`{${name}}`, () => value),
      translations[locale.value][key],
    );
  }
  function toggleTheme() {
    theme.value = theme.value === "dark" ? "light" : "dark";
  }
  function toggleLocale() {
    locale.value = locale.value === "tr" ? "en" : "tr";
  }
  return { locale, theme, page, t, toggleTheme, toggleLocale };
});
